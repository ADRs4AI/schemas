#!/usr/bin/env python3
"""update_indexes.py — regenerate BOTH front doors from v1/template/*.

Scans published versions (immutable dirs) and rewrites the machine index
(llms.txt) AND the pinned-version rows of the human index (index.html,
between the pinned:start/pinned:end markers — fail-loud if they vanish,
because a silently-stale human door is exactly the bug this fixes: the
founder caught index.html still showing v3.11.6 the hour v3.12.0 published,
2026-10-20). Stdlib only. Formerly update_llms_txt.py.
"""
import os, re, sys

BASE = "https://schemas.adrs.systems"
vers = sorted(
    (d for d in os.listdir("v1/template")
     if d != "latest" and os.path.isdir(os.path.join("v1/template", d))),
    key=lambda v: [int(x) for x in re.findall(r"\d+", v)], reverse=True)

lines = [
    "# ADRs for AI (ADRs4AI) — teaching bundles",
    "",
    "> Model-native teaching bundles of the ADRs4AI methodology: each released",
    "> version of the canonical human-AI collaboration template, concatenated into",
    "> one fetchable markdown file — one-file access to the whole picture, so a",
    "> model that encounters one of the subfiles can automatically, painlessly",
    "> recover the full context.",
    "",
    "## The bundle",
    "",
    f"- [Latest (mutable alias, re-resolved at use)]({BASE}/v1/template/latest/template-latest.md)",
]
for v in vers:
    lines.append(f"- [{v} (immutable)]({BASE}/v1/template/{v}/template-{v}.md)")
lines += [
    "",
    "## Provenance",
    "",
    "- Source: https://github.com/ADRs4AI/human-ai-collaboration-template-A (Apache-2.0; the license and NOTICE travel in every bundle)",
    "- Cite the living work: concept DOI 10.5281/zenodo.23303469",
    "- Publisher: https://github.com/ADRs4AI/schemas — versioned URLs are immutable after publication; `latest/` is the one mutable alias",
    "",
]
open("llms.txt", "w").write("\n".join(lines))
print(f"llms.txt: {len(vers)} version(s) indexed")

# --- the human door: index.html's pinned rows, between the markers ---
START, END = "<!-- pinned:start", "<!-- pinned:end -->"
html = open("index.html", encoding="utf-8").read()
if START not in html or END not in html:
    sys.exit("update_indexes: index.html lost its pinned:start/pinned:end "
             "markers — refusing to publish a silently-stale human index")
rows = "\n".join(
    f'  <li><a href="/v1/template/{v}/"><code>/v1/template/{v}/</code></a>'
    f" — pinned (immutable)</li>" for v in vers)
html = re.sub(
    re.escape(START) + r".*?" + re.escape(END),
    f"{START} — these rows are REGENERATED by scripts/update_indexes.py on "
    f"every publish; edit the row template there, never these lines -->\n"
    f"{rows}\n  {END}",
    html, count=1, flags=re.S)
open("index.html", "w", encoding="utf-8").write(html)
print(f"index.html: {len(vers)} pinned row(s) regenerated")
